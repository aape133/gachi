"""Writes THIRD-PARTY-LICENSES.md: every Rust package in the Windows build, its license, and
the license texts themselves as the packages carry them (their copyright lines included).

    python scripts/third_party_licenses.py

Run it again after changing dependencies. Packages only the tests use are left out. A text
that many packages share word for word is printed once, with the packages under it.
"""
import collections
import hashlib
import json
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = "x86_64-pc-windows-msvc"
# (file names packages keep their license texts and notices under)
NAMES = re.compile(r"^(licen[sc]e|copying|copyright|notice|unlicense|authors|patents)", re.I)

HEAD = """# Third-party software in gachi

gachi itself is under the GNU General Public License, version 3 (see [LICENSE](LICENSE)).
It is built with the software below, each under its own license. All of these licenses
allow use in a GPLv3 work. The table lists every package; the license texts, with each
package's own copyright lines, follow it.

Not from crates.io:

- **Steinberg ASIO SDK** (the app's audio device access): used under the SDK's GPLv3 option.
  Not in this repository; fetched when building. ASIO is a registered trademark of
  Steinberg Media Technologies GmbH.
- **Steinberg VST 3 SDK** (the plugin's interface, through the `vst3` package's bindings):
  MIT License, Copyright (c) Steinberg Media Technologies GmbH. VST is a registered
  trademark of Steinberg Media Technologies GmbH.
- **Microsoft WebView2 runtime** (draws the window): part of Windows, not distributed by gachi.
- **Pretendard** and **Pretendard JP** (the fonts; Pretendard JP builds on Source Han Sans, Inter and M PLUS 1p), SIL Open Font License 1.1: `ui/fonts/LICENSE.txt`.
"""


def packages():
    meta = json.loads(subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--filter-platform", TARGET],
        cwd=ROOT, capture_output=True, text=True, encoding="utf-8", check=True).stdout)
    ours = set(meta["workspace_members"])
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    seen, todo = set(), list(ours)
    while todo:
        i = todo.pop()
        if i in seen:
            continue
        seen.add(i)
        for dep in nodes[i]["deps"]:
            # (what only tests and examples use is not in what ships)
            if any(k.get("kind") != "dev" for k in dep["dep_kinds"]):
                todo.append(dep["pkg"])
    return sorted((p for p in meta["packages"] if p["id"] in seen and p["id"] not in ours),
                  key=lambda p: (p["name"].lower(), p["version"]))


def texts(pkg):
    """The package's license files, as (file name, text)."""
    folder = pathlib.Path(pkg["manifest_path"]).parent
    out = []
    for f in sorted(folder.iterdir()):
        if f.is_file() and NAMES.match(f.name) and f.stat().st_size < 200_000:
            try:
                out.append((f.name, f.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").strip()))
            except OSError:
                pass
    return out


def main():
    pkgs = packages()
    by_license = collections.Counter(p.get("license") or "see its files" for p in pkgs)
    # one entry per distinct text: the packages that carry it, in order
    shared = collections.OrderedDict()
    bare = []
    for p in pkgs:
        found = texts(p)
        if not found:
            bare.append(p)
        for name, text in found:
            key = hashlib.sha256(re.sub(r"\s+", " ", text).encode()).hexdigest()
            shared.setdefault(key, (text, []))[1].append(f"{p['name']} {p['version']} ({name})")

    out = [HEAD, f"## Rust packages ({len(pkgs)}, for the Windows build)\n",
           "Generated by `scripts/third_party_licenses.py` from `cargo metadata`; run it again after changing dependencies.\n",
           "By license: " + ", ".join(f"{k}: {v}" for k, v in by_license.most_common()) + "\n",
           "| Package | Version | License | Source |", "|---|---|---|---|"]
    for p in pkgs:
        src = p.get("repository") or p.get("homepage") or f"https://crates.io/crates/{p['name']}"
        out.append(f"| {p['name']} | {p['version']} | {p.get('license') or 'see its files'} | {src} |")

    out += ["", "## License texts\n",
            "As the packages carry them. A text several packages share word for word is given once.\n"]
    if bare:
        out.append("These packages come without a license file of their own; their license is the one "
                   "the table names, by the authors their package states:\n")
        for p in bare:
            who = ", ".join(p.get("authors") or []) or "its authors"
            out.append(f"- {p['name']} {p['version']}: {p.get('license')}, {who}")
        out.append("")
    # the most shared first
    for text, users in sorted(shared.values(), key=lambda e: -len(e[1])):
        fence = "````"
        out += [f"### {users[0]}" + (f" and {len(users) - 1} more" if len(users) > 1 else ""), ""]
        if len(users) > 1:
            out += ["Carried by: " + ", ".join(users) + ".", ""]
        out += [fence + "text", text.replace(fence, "''''"), fence, ""]

    path = ROOT / "THIRD-PARTY-LICENSES.md"
    path.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"{len(pkgs)} packages, {len(shared)} distinct texts, {len(bare)} without a file, {path.stat().st_size // 1024} KB")
    for p in bare:
        print("  no license file:", p["name"], p["version"], p.get("license"))


if __name__ == "__main__":
    main()
